// Icons drawn from CSS (::before/::after).
const CSS_ICONS = ["check2", "plus-lg", "dash-lg", "chevron-down", "arrows-angle-expand"];

function read(name) {
  const file = path.join(SRC, `${name}.svg`);
  if (!fs.existsSync(file)) throw new Error(`Unknown bootstrap icon: ${name}`);
  return fs.readFileSync(file, "utf8");
}

const inner = (svg) =>
  svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/\s+/g, " ")
    .trim();

const all = [...new Set([...UI_ICONS, ...CHOOSABLE_ICONS])].sort();
const map = Object.fromEntries(all.map((n) => [n, inner(read(n))]));

fs.writeFileSync(
  path.join(root, "src/components/ui/icons.generated.js"),
  `// GENERATED by scripts/build-icons.js — do not edit. Source: bootstrap-icons (MIT).\n` +
    `export const ICONS = ${JSON.stringify(map, null, 1)};\n\n` +
    `export const CHOOSABLE_ICONS = ${JSON.stringify(CHOOSABLE_ICONS)};\n`,
);

fs.writeFileSync(
  path.join(root, "src/components/ui/icons.client.generated.js"),
  `// GENERATED by scripts/build-icons.js — do not edit. Client-bundle subset.\n` +
    `export const CLIENT_ICONS = ${JSON.stringify(
      Object.fromEntries(CLIENT_ICONS.map((n) => [n, map[n] ?? inner(read(n))])),
      null,
      1,
    )};\n`,
);

const dataUri = (svg) =>
  `url("data:image/svg+xml,${svg
    .replace(/\s+/g, " ")
    .replace(/"/g, "'")
    .replace(/#/g, "%23")
    .replace(/</g, "%3C")
    .replace(/>/g, "%3E")
    .trim()}")`;

fs.writeFileSync(
  path.join(root, "src/styles/_icons.generated.scss"),
  `// GENERATED by scripts/build-icons.js — do not edit. Source: bootstrap-icons (MIT).\n` +
    `$icons: (\n${CSS_ICONS.map((n) => `  "${n}": ${dataUri(read(n))},`).join("\n")}\n);\n`,
);

console.log(`✓ ${all.length} component icons, ${CSS_ICONS.length} CSS icons generated`);
